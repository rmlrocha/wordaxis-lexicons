# Hunspell affix expansion
# --------------------------------------------------------------------------

class AffixRule:
    __slots__ = ("strip", "add", "cont", "cond")

    def __init__(self, kind, strip, add, cond):
        self.strip = "" if strip == "0" else strip
        cont = ""
        if "/" in add:
            add, cont = add.split("/", 1)
        self.add = "" if add == "0" else add
        self.cont = cont
        if cond == ".":
            self.cond = None
        elif kind == "SFX":
            self.cond = re.compile("(?:" + cond + ")$")
        else:
            self.cond = re.compile("^(?:" + cond + ")")


class AffixClass:
    def __init__(self, kind, flag, cross):
        self.kind = kind
        self.flag = flag
        self.cross = cross
        self.rules = []


class Hunspell:
    def __init__(self, aff_path, dic_path, skip_rules=None):
        """`skip_rules` maps an affix flag to the appends ("emo", "dão") whose rules are ignored."""
        self.skip_rules = skip_rules or {}
        self.prefixes = {}
        self.suffixes = {}
        self.forbidden = None
        self.needaffix = None
        self._parse_aff(aff_path)
        self.dic_path = dic_path

    def _parse_aff(self, path):
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
        i = 0
        while i < len(lines):
            parts = lines[i].split()
            i += 1
            if not parts or parts[0].startswith("#"):
                continue
            key = parts[0]
            if key == "FORBIDDENWORD":
                self.forbidden = parts[1]
            elif key == "NEEDAFFIX":
                self.needaffix = parts[1]
            elif key in ("PFX", "SFX") and len(parts) == 4 and parts[2] in ("Y", "N"):
                cls = AffixClass(key, parts[1], parts[2] == "Y")
                count = int(parts[3])
                for _ in range(count):
                    rp = lines[i].split()
                    i += 1
                    if len(rp) < 5:
                        continue
                    rule = AffixRule(key, rp[2], rp[3], rp[4])
                    if rule.add not in self.skip_rules.get(parts[1], ()):
                        cls.rules.append(rule)
                (self.prefixes if key == "PFX" else self.suffixes)[cls.flag] = cls

    def _apply_sfx(self, word, cls):
        for r in cls.rules:
            if r.strip and not word.endswith(r.strip):
                continue
            if r.cond is not None and not r.cond.search(word):
                continue
            base = word[: len(word) - len(r.strip)] if r.strip else word
            yield base + r.add, r.cont

    def _apply_pfx(self, word, cls):
        for r in cls.rules:
            if r.strip and not word.startswith(r.strip):
                continue
            if r.cond is not None and not r.cond.match(word):
                continue
            yield r.add + word[len(r.strip):], r.cont

    def expand(self, word, flags):
        """Yield every surface form licensed by `word` + `flags`."""
        if self.forbidden and self.forbidden in flags:
            return
        if not (self.needaffix and self.needaffix in flags):
            yield word
        sfx_forms = []
        for fl in flags:
            cls = self.suffixes.get(fl)
            if not cls:
                continue
            for form, cont in self._apply_sfx(word, cls):
                if self.forbidden and self.forbidden in cont:
                    continue
                yield form
                sfx_forms.append((form, cls.cross))
                # One level of continuation (two-fold suffixes).
                for cfl in cont:
                    ccls = self.suffixes.get(cfl)
                    if ccls:
                        for f2, _ in self._apply_sfx(form, ccls):
                            yield f2
        for fl in flags:
            cls = self.prefixes.get(fl)
            if not cls:
                continue
            for form, _ in self._apply_pfx(word, cls):
                yield form
            if cls.cross:
                for sform, scross in sfx_forms:
                    if scross:
                        for form, _ in self._apply_pfx(sform, cls):
                            yield form

    def entries(self):
        """Yield (word, flags, morphology) for every .dic line."""
        with open(self.dic_path, encoding="utf-8-sig") as f:
            first = True
            for line in f:
                line = line.rstrip("\n")
                if first:
                    first = False
                    if line.strip().isdigit():
                        continue
                if not line.strip():
                    continue
                morph = ""
                if "\t" in line:
                    line, morph = line.split("\t", 1)
                line = line.strip()
                if "/" in line:
                    word, flags = line.split("/", 1)
                else:
                    word, flags = line, ""
                yield word, flags, morph


