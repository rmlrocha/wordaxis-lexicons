# Foreign words (estrangeirismos) are not playable in the Portuguese packs.
# 1. Natura tags loanwords with ORIG=<language>; those entries are excluded (and,
#    for VERO, which has no tags, the same headwords and their plurals). Already
#    adapted forms tagged with an origin stay.
PT_PT_FOREIGN = re.compile(r"ORIG=")
FOREIGN_KEPT = {"impacte", "cânon", "práxis", "códex", "czar", "czarina", "telex", "videoclipe", "videoclube"}
# 2. Spellings Portuguese orthography doesn't use: th, ph, sh, ck, doubled
#    consonants, s + consonant at the start, a final b/c/d/f/g/h/j/p/q/t/v (with
#    or without plural s), or no vowel at all (symbols and abbreviations: cm, sr).
#    This catches untagged loanwords (jazz, habitat, deficit, scanner) and VERO's
#    many foreign-spelled terms.
PT_VOWELS = "aeiouáéíóúâêôãõàü"
FOREIGN_SPELLING = re.compile(rf"^s[^{PT_VOWELS}]|th|ph|sh|ck|zz|ff|tt|pp|gg|dd|bb|nn|tz|[bcdfghjpqtv]s?$")
# Portuguese words those rules would catch: "sob", "connosco", quartzo, hertziano,
# unit names, bíceps/fórceps, and words derived from proper names.
FOREIGN_SPELLING_KEPT = re.compile(
    r"^(sob|connosco)$|quartz|hertz|(volt|farad|coulomb|erg|parsec)s?$|ceps$|sportinguist|garrett")
# 3. Everyday loanwords that stay playable despite rules 1 and 2: food, music and
#    sport words used daily in Portuguese (editorial list; extend as needed).
FOREIGN_ALLOWED = {
    "pizza", "pizzas", "pizzaria", "pizzarias", "pizzaiolo", "pizzaiolos",
    "sushi", "sushis", "sashimi", "sashimis", "cappuccino", "cappuccinos", "croissant", "croissants",
    "spaghetti", "jazz", "jazzista", "jazzistas", "rock", "rap", "punk", "punks", "reggae",
    "ballet", "surf", "golf",
}


def has_foreign_spelling(word):
    if not any(ch in PT_VOWELS for ch in word):
        return True
    return bool(FOREIGN_SPELLING.search(word)) and not FOREIGN_SPELLING_KEPT.search(word)


def foreign_headwords(locale):
    """pt-PT entries tagged with a foreign origin, as headwords (for VERO)."""
    if locale != "pt-BR":
        return set()
    words = set()
    with open(os.path.join(SRC, "pt_PT", "pt_PT.dic"), encoding="utf-8") as f:
        for line in f:
            if "\t" in line and PT_PT_FOREIGN.search(line.split("\t", 1)[1]):
                words.add(line.split("\t", 1)[0].split("/", 1)[0].strip())
    return words - FOREIGN_KEPT


def fold(word, preserved):
    """Upper-case and strip diacritics, keeping `preserved` letters intact."""
    out = []
    for ch in word.upper():
        if ch in preserved:
            out.append(ch)
            continue
        decomposed = unicodedata.normalize("NFD", ch)
        out.append("".join(c for c in decomposed if unicodedata.category(c) != "Mn"))
    return unicodedata.normalize("NFC", "".join(out))


def is_playable_surface(word):
    """Word-game admission rules applied to the surface (accented) form."""
    if len(word) < MIN_LEN:
        return False
    if word != word.lower():
        return False                      # proper nouns, acronyms, abbreviations
    for ch in word:
        if not unicodedata.category(ch).startswith("L"):
            return False                  # hyphens, apostrophes, dots, digits
    return True


EDITORIAL = os.path.join(HERE, "LexiconEditorial")


def editorial_exclusions(locale, forms, stats):
    """Words a reviewer marked as not acceptable in play (Tools/lexicon_review.py), one per
    line as spelled on the tiles (upper case, folded: "TOMOS"); "#" starts a comment. Every
    spelling that folds to a listed word is removed."""
    path = os.path.join(EDITORIAL, f"{locale}-excluded.txt")
    if not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8") as f:
        words = {line.split("#")[0].strip().upper() for line in f} - {""}
    preserved = set(LANGS[locale]["preserved"])
    removed = {w for w in forms if fold(w, preserved) in words}
    stats["excluded_editorial"] = len(removed)
    stats["excluded_editorial_list"] = " ".join(sorted(removed))
    return removed


def collect_words(locale, cfg, stats):
    forms = set()
    if cfg["source"] == "enable":
        with open(os.path.join(SRC, "en_US", "enable1.txt"), encoding="ascii") as f:
            for line in f:
                w = line.strip()
                stats["source_entries"] += 1
                if w in EN_INTERJECTIONS:
                    stats["excluded_interjections"] += 1
                    continue
                if w and is_playable_surface(w):
                    forms.add(unicodedata.normalize("NFC", w))
        stats["excluded_interjection_list"] = " ".join(sorted(EN_INTERJECTIONS & set(open(
            os.path.join(SRC, "en_US", "enable1.txt"), encoding="ascii").read().split())))
        return forms - editorial_exclusions(locale, forms, stats)

    hs = Hunspell(os.path.join(SRC, cfg["aff"]), os.path.join(SRC, cfg["dic"]), cfg.get("skipRules"))
    interjections = interjection_headwords(locale)
    interjection_forms = set()
    foreign = foreign_headwords(locale)
    foreign_forms = set()
    for word, flags, morph in hs.entries():
        stats["source_entries"] += 1
        if locale == "pt-PT" and (PT_PT_EXCLUDED_CATS.search(morph) or PT_PT_EXCLUDED_SUBCATS.search(morph)):
            stats["excluded_by_category"] += 1
            continue
        if word[:1] != word[:1].lower():
            stats["excluded_capitalised_root"] += 1
            continue
        tagged = PT_PT_INTERJECTION.search(morph) if locale == "pt-PT" else word in interjections
        is_interjection = bool(tagged) and word not in INTERJECTIONS_KEPT
        # Only the interjection itself and its plural are removed; other forms the
        # entry generates are ordinary words (VERO derives "puma" from "pum/D").
        excluded_here = interjection_and_plurals(word) if is_interjection else set()
        # A pt-PT loanword entry is excluded with every form it generates; for VERO
        # only the pt-PT headword and its plurals are known to be foreign.
        is_foreign_entry = locale == "pt-PT" and bool(PT_PT_FOREIGN.search(morph)) and word not in FOREIGN_KEPT
        foreign_here = interjection_and_plurals(word) if word in foreign else set()
        for form in hs.expand(word, flags):
            stats["generated_forms"] += 1
            form = unicodedata.normalize("NFC", form)
            if not is_playable_surface(form):
                continue
            if form in excluded_here:
                interjection_forms.add(form)
            elif (is_foreign_entry or form in foreign_here) and form not in FOREIGN_ALLOWED:
                foreign_forms.add(form)
            else:
                forms.add(form)
    # Interjections are excluded unless another entry produces the same spelling:
    # "basta" (bastar), "fora" stay; "pum", "puns", "caramba", "olá" go.
    removed = sorted(interjection_forms - forms)
    stats["excluded_interjections"] = len(removed)
    stats["excluded_interjection_list"] = " ".join(removed)
    # Tagged loanwords go unless a Portuguese entry spells the same; then foreign spellings.
    spelled = {w for w in forms if has_foreign_spelling(w) and w not in FOREIGN_ALLOWED}
    forms -= spelled
    foreign_removed = sorted((foreign_forms - forms) | spelled)
    stats["excluded_foreign"] = len(foreign_removed)
    stats["excluded_foreign_list"] = " ".join(foreign_removed)
    forms -= editorial_exclusions(locale, forms, stats)
    rejected = hunspell_rejections(cfg, forms)
    if rejected is None:
        print("  warning: hunspell not found; generated forms not cross-checked", file=sys.stderr)
        stats["hunspell_crosscheck"] = "skipped"
    else:
        stats["hunspell_crosscheck"] = "passed"
        stats["rejected_by_hunspell"] = len(rejected)
        forms -= rejected
    return forms


def hunspell_rejections(cfg, forms):
    """Cross-check generated forms with the reference Hunspell binary, if present."""
    import shutil
    import subprocess
    exe = shutil.which("hunspell")
    if not exe:
        return None
    dic_base = os.path.join(SRC, cfg["dic"])[:-4]
    proc = subprocess.run(
        [exe, "-d", dic_base, "-L", "-i", "UTF-8"],
        input="\n".join(sorted(forms)).encode("utf-8"),
        stdout=subprocess.PIPE, check=True,
    )
    return {unicodedata.normalize("NFC", w) for w in proc.stdout.decode("utf-8").split("\n") if w}


