DEFAULT_CAPS = {}


def derive_tiles(folded_words, threshold, caps=None):
    """
    Letter frequencies are measured over distinct folded words of 2-8 letters
    (the lengths that matter most in play). Counts are allocated with the
    largest-remainder method over TOTAL_TILES - BLANKS, with a minimum of one
    tile per letter; values follow inverse frequency on a 1..10 scale.
    """
    counter = Counter()
    for w in folded_words:
        if 2 <= len(w) <= 8:
            counter.update(w)
    total = sum(counter.values())
    freqs = {ch: n / total for ch, n in counter.items()}
    alphabet = sorted([ch for ch, f in freqs.items() if f >= threshold], key=letter_sort_key)

    budget = TOTAL_TILES - BLANKS
    kept_total = sum(freqs[ch] for ch in alphabet)
    raw = {ch: freqs[ch] / kept_total * budget for ch in alphabet}
    caps = dict(DEFAULT_CAPS, **(caps or {}))
    counts = {ch: 1 for ch in alphabet}
    # Highest-deficit allocation: each remaining tile goes to the letter whose
    # current count is furthest below its proportional share.
    for _ in range(budget - len(alphabet)):
        candidates = [ch for ch in alphabet if counts[ch] < caps.get(ch, 12)]
        best = max(candidates, key=lambda ch: (raw[ch] - counts[ch], raw[ch]))
        counts[best] += 1

    values = {}
    for ch in alphabet:
        f = freqs[ch]
        if f >= 0.075:
            v = 1
        elif f >= 0.045:
            v = 1 if counts[ch] >= 6 else 2
        elif f >= 0.03:
            v = 2
        elif f >= 0.02:
            v = 3
        elif f >= 0.012:
            v = 4
        elif f >= 0.006:
            v = 5
        elif f >= 0.003:
            v = 8
        else:
            v = 10
        values[ch] = v
    return alphabet, counts, values, freqs


def letter_sort_key(ch):
    base = unicodedata.normalize("NFD", ch)[0]
    return (base, ch)


# --------------------------------------------------------------------------
# DAWG construction (Daciuk et al. incremental algorithm on sorted input)
# --------------------------------------------------------------------------

class Node:
    __slots__ = ("terminal", "edges", "id")
    _next = 0

    def __init__(self):
        self.terminal = False
        self.edges = {}  # letter index -> Node
        self.id = Node._next
        Node._next += 1

    def key(self):
        return (self.terminal, tuple((l, n.id) for l, n in sorted(self.edges.items())))


def build_dawg(words):
    """`words`: sorted list of tuples of letter indices."""
    root = Node()
    register = {}
    unchecked = []  # (parent, letter, child)
    previous = ()

    def minimize(down_to):
        while len(unchecked) > down_to:
            parent, letter, child = unchecked.pop()
            k = child.key()
            if k in register:
                parent.edges[letter] = register[k]
            else:
                register[k] = child

    for word in words:
        common = 0
        for a, b in zip(word, previous):
            if a != b:
                break
            common += 1
        minimize(common)
        node = unchecked[-1][2] if unchecked else root
        for letter in word[common:]:
            nxt = Node()
            node.edges[letter] = nxt
            unchecked.append((node, letter, nxt))
            node = nxt
        node.terminal = True
        previous = word
    minimize(0)
    return root


def serialize_dawg(root):
    """
    Edge-list encoding, one little-endian UInt32 per edge:
      bits 0-5   letter index (0..63)
      bit  6     terminal: a word ends after following this edge
      bit  7     last edge of its node's list
      bits 8-31  index of the child's first edge (0 = child has no edges)
    Edge 0 is a sentinel. The header stores the root's first edge index.
    """
    edges = [0]
    first_edge = {}
    # Post-order layout so that every child's list exists before its parent.
    order = []
    seen = set()
    stack = [(root, False)]
    while stack:
        node, done = stack.pop()
        if done:
            order.append(node)
            continue
        if node.id in seen:
            continue
        seen.add(node.id)
        stack.append((node, True))
        for _, child in sorted(node.edges.items(), reverse=True):
            if child.id not in seen:
                stack.append((child, False))
    for node in order:
        if not node.edges:
            first_edge[node.id] = 0
            continue
        start = len(edges)
        items = sorted(node.edges.items())
        for i, (letter, child) in enumerate(items):
            v = letter & 0x3F
            if child.terminal:
                v |= 1 << 6
            if i == len(items) - 1:
                v |= 1 << 7
            v |= first_edge[child.id] << 8
            edges.append(v)
        first_edge[node.id] = start
    if len(edges) >= (1 << 24):
        raise SystemExit("DAWG too large for 24-bit child indices")
    return edges, first_edge[root.id]


def write_dawg(path, edges, root_index, alphabet_size, word_count):
    import struct
    with open(path, "wb") as f:
        # magic, format version, alphabet size, root edge index, edge count, word count
        f.write(b"WAXD")
        f.write(struct.pack("<IIIII", 1, alphabet_size, root_index, len(edges), word_count))
        f.write(struct.pack("<%dI" % len(edges), *edges))


def write_display_index(path, entries, block_size=512):
    """
    Block-compressed sorted map: folded word -> display forms.
      "WAXF", UInt32 version, UInt32 block count
      per block: UInt32 offset, UInt32 length, UInt16 key length, key (UTF-8)
      blocks: raw DEFLATE (Apple COMPRESSION_ZLIB) of "KEY\tform|form\n" lines
    """
    import struct
    blocks = [entries[i:i + block_size] for i in range(0, len(entries), block_size)]
    payloads = []
    for blk in blocks:
        text = "".join(k + "\t" + v + "\n" for k, v in blk).encode("utf-8")
        c = zlib.compressobj(9, zlib.DEFLATED, -15)
        payloads.append(c.compress(text) + c.flush())
    index = b""
    keys = [blk[0][0].encode("utf-8") for blk in blocks]
    header_len = 12 + sum(10 + len(k) for k in keys)
    offset = header_len
    for k, pl in zip(keys, payloads):
        index += struct.pack("<IIH", offset, len(pl), len(k)) + k
        offset += len(pl)
    with open(path, "wb") as f:
        f.write(b"WAXF" + struct.pack("<II", 1, len(blocks)))
        f.write(index)
        for pl in payloads:
            f.write(pl)


