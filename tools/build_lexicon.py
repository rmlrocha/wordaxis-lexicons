def playable_words(locale, stats):
    """The pack's final word list: upstream forms, filtered, folded to tile letters.
    Also used by Tools/export_mpl_source.py, so the published lists match the app."""
    cfg = LANGS[locale]
    forms = collect_words(locale, cfg, stats)
    preserved = set(cfg["preserved"])

    folded_to_display = defaultdict(set)
    for w in forms:
        folded_to_display[fold(w, preserved)].add(w)

    # Discard folded words containing characters outside A-Z + preserved.
    allowed_chars = set(LATIN) | preserved
    folded = {w for w in folded_to_display if set(w) <= allowed_chars and MIN_LEN <= len(w) <= MAX_LEN}

    tiles = derive_tiles(folded, cfg["letterThreshold"], cfg.get("tileCaps"))
    alpha_set = set(tiles[0])
    playable = sorted(w for w in folded if set(w) <= alpha_set)
    stats["dropped_for_letters"] = len(folded) - len(playable)
    stats["folded_words"] = len(folded)
    return forms, folded_to_display, tiles, sorted(allowed_chars - alpha_set), playable


def build(locale, out_dir):
    cfg = LANGS[locale]
    stats = Counter()
    preserved = set(cfg["preserved"])
    forms, folded_to_display, tiles, dropped_letters, playable = playable_words(locale, stats)
    alphabet, counts, values, freqs = tiles

    index = {ch: i for i, ch in enumerate(alphabet)}
    encoded = sorted(tuple(index[c] for c in w) for w in playable)
    Node._next = 0
    root = build_dawg(encoded)
    edges, root_index = serialize_dawg(root)

    dest = os.path.join(out_dir, locale)
    os.makedirs(dest, exist_ok=True)
    write_dawg(os.path.join(dest, "lexicon.dawg"), edges, root_index, len(alphabet), len(playable))

    # Common words: the most frequent words of everyday usage that are also in the
    # full lexicon. Used only to make the Easy/Normal AI play natural words; the
    # full lexicon still decides what is valid.
    common = common_words(cfg, forms, preserved, set(playable))
    Node._next = 0
    croot = build_dawg(sorted(tuple(index[c] for c in w) for w in common))
    cedges, croot_index = serialize_dawg(croot)
    write_dawg(os.path.join(dest, "common.dawg"), cedges, croot_index, len(alphabet), len(common))

    # Display forms only where folding lost information.
    entries = []
    for w in playable:
        disp = sorted(folded_to_display[w])
        if len(disp) == 1 and disp[0].upper() == w:
            continue
        entries.append((w, "|".join(disp)))
    write_display_index(os.path.join(dest, "display.idx"), entries)
    stale = os.path.join(dest, "display.txt.z")
    if os.path.exists(stale):
        os.remove(stale)

    with open(os.path.join(dest, "lexicon.dawg"), "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()

    pack = {
        "formatVersion": 1,
        "id": locale,
        "name": cfg["name"],
        "nativeName": cfg["nativeName"],
        "dictionaryVersion": cfg["dictionaryVersion"],
        "lexiconSHA256": digest,
        "wordCount": len(playable),
        "alphabet": [
            {"letter": ch, "count": counts[ch], "value": values[ch]} for ch in alphabet
        ],
        "blankCount": BLANKS,
        "vowels": [ch for ch in alphabet if ch in "AEIOU"],
        "normalization": {
            "uppercase": True,
            "foldDiacritics": True,
            "preservedLetters": sorted(preserved),
            "unicodeForm": "NFC",
        },
        "wordRules": {
            "minLength": MIN_LEN,
            "maxLength": MAX_LEN,
            "inflectedVerbs": "allowed" if cfg["source"] == "hunspell" else "allowed (as listed by source)",
            "plurals": "allowed",
            "properNouns": "excluded",
            "interjections": "excluded unless also another part of speech",
            **({"foreignWords": "excluded (tagged loanwords and non-Portuguese spellings)"} if cfg["source"] == "hunspell" else {}),
            "abbreviations": "excluded",
            "acronyms": "excluded",
            "hyphenatedWords": "excluded",
            "regionalVocabulary": "as listed by source",
            "accentedCharacters": "folded to base tile letter" + (" (Ç is its own tile)" if preserved else ""),
        },
        "license": license_info(locale),
        "commonWords": {
            "count": len(common),
            "source": "FrequencyWords (Hermit Dave), OpenSubtitles 2018 — " + cfg["frequency"].split("/")[-1],
            "license": "CC BY-SA 4.0; the derived common-word list is distributed under CC BY-SA 4.0",
            "url": "https://github.com/hermitdave/FrequencyWords",
            "modifications": "Top 50,000 surface forms (top 10,000 for words of 2-4 letters; words without vowels skipped) intersected with this pack's lexicon, then folded.",
        },
    }
    with open(os.path.join(dest, "pack.json"), "w", encoding="utf-8") as f:
        json.dump(pack, f, ensure_ascii=False, indent=2)

    report = dict(stats)
    report.update({
        "surface_forms": len(forms),
        "folded_words": stats["folded_words"],
        "playable_words": len(playable),
        "common_words": len(common),
        "dawg_edges": len(edges),
        "dropped_letters": dropped_letters,
        "excluded_interjections": stats.get("excluded_interjection_list", ""),
        "excluded_foreign": stats.get("excluded_foreign_list", ""),
        "frequencies": {ch: round(freqs.get(ch, 0), 5) for ch in sorted(freqs, key=letter_sort_key)},
    })
    report_dir = os.path.join(HERE, "LexiconReports")
    os.makedirs(report_dir, exist_ok=True)
    with open(os.path.join(report_dir, locale + ".json"), "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    print(locale, json.dumps({k: report[k] for k in ("surface_forms", "playable_words", "dawg_edges", "dropped_letters")}, ensure_ascii=False))


SHORT_WORD_RANK = 10_000
SHORT_WORD_LENGTH = 4


def common_words(cfg, surface_forms, preserved, playable):
    """Folded words that appear in the frequency list *with the same spelling* as a
    lexicon surface form (so accent typos in subtitles can't sneak in).
    Short tokens in subtitles are often names, Latin or interjections ("quo",
    "manu", "ji"), so words of up to SHORT_WORD_LENGTH letters must rank in the
    top SHORT_WORD_RANK. Words without a vowel (unit symbols like "cm") are skipped."""
    out = set()
    with open(os.path.join(SRC, cfg["frequency"]), encoding="utf-8") as f:
        for rank, line in enumerate(f, start=1):
            parts = line.split()
            if not parts:
                continue
            w = unicodedata.normalize("NFC", parts[0])
            if len(w) <= SHORT_WORD_LENGTH and rank > SHORT_WORD_RANK:
                continue
            if not any(fold(c, set()) in "AEIOU" for c in w):
                continue
            if w in surface_forms:
                folded = fold(w, preserved)
                if folded in playable:
                    out.add(folded)
    return out


